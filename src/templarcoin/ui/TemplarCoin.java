    private void btSignActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btSignActionPerformed
        try {
            double amount = TemplarServices.getAmount(user, blockchain);
            double value = Double.parseDouble(txtTransactionvalue.getText());
            if (value > amount) {
                JOptionPane.showMessageDialog(this, "Saldo insuficiente", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            Transaction tr = new Transaction(
                    user, // sempre o utilizador com sessão iniciada: o saldo verificado acima é o dele
                    txtNameReceiver.getText(),
                    value,
                    privKey);
            txtSignature.setText(tr.getSignature());
            //interface não bloqueante
           new Thread(() -> {
                try {
                    txtWorking.setVisible(true);
                    btSign.setEnabled(false);
                    blockchain.addData(tr.toBase64());
                    updateGui();
                    txtWorking.setVisible(false);
                    btSign.setEnabled(true);

                } catch (IOException ex) {
                    System.getLogger(TemplarCoin.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
                }

            }).start();

        } catch (Exception ex) {
            System.getLogger(TemplarCoin.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }

    }//GEN-LAST:event_btSignActionPerformed

    private void lstBlockChainValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_lstBlockChainValueChanged
        if (lstBlockChain.getSelectedIndex() >= 0) {
            Block b = (Block) lstBlockChain.getSelectedValues()[0];
            txtData.setText(b.getData());
            txtPrevHash.setText(b.getPreviousHash());
            txtConsensus.setText("(" + b.getDificulty() + ")" + b.getNonce());
            txtCurrentHash.setText(b.getCurrentHash());

            try {
                //converter para Transação
                // um bloco pode ter uma Transaction ou um registo de bilhetes
                Object t = Conversion.stringToObject(b.getData());
                txtObject.setText(t.toString());
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, ex.getMessage(), "Erro de conversão", JOptionPane.ERROR_MESSAGE);
            }

        }
    }//GEN-LAST:event_lstBlockChainValueChanged


