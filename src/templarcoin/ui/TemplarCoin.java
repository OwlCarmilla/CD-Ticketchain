    public void iniMyComponents() {
        try {
            this.blockchain = new BlockChain();
            txtSenderName.setText(user);
            // vários utilizadores podem estar abertos ao mesmo tempo: fechar uma janela não fecha as outras
            setTitle("TemplarCoin - " + user);
            setDefaultCloseOperation(javax.swing.WindowConstants.DISPOSE_ON_CLOSE);
            // separador "Bilhetes", atualizado sempre que é selecionado
            ticketservice.ui.TicketsPanel tickets
                    = new ticketservice.ui.TicketsPanel(user, privKey, pubKey, blockchain, this::updateGui);
            jTabbedPane1.addTab("Bilhetes", tickets);
            jTabbedPane1.addChangeListener(e -> {
                if (jTabbedPane1.getSelectedComponent() == tickets) {
                    tickets.refresh();
                }
            });
            updateGui();
        } catch (Exception ex) {
            System.getLogger(TemplarCoin.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
    }

    public void updateGui() {
        // lê os blocos adicionados por outras janelas
        blockchain.reload();
        //interfaces não bloqueantes
        SwingUtilities.invokeLater(() -> { // Thread
//--------------------------------------------------
            try {
                txtUserAmount.setText(TemplarServices.getAmount(user, this.blockchain) + "");
                StringBuilder txt = new StringBuilder("Carteira Digital de " + user + "\n");
                for (Block blk : blockchain.getChain()) {
                    try {
                        Transaction tr = (Transaction) Conversion.stringToObject(blk.getData());
                        if (tr.getFrom().equals(this.user) || tr.getTo().equals(this.user)) {
                            txt.append(tr.toString()).append("\n");
                        }
                    } catch (Exception e) {
                    }
                }
                txtTransactions.setText(txt.toString());

                DefaultListModel model = new DefaultListModel<>();
                for (Block b : blockchain.getChain()) {
                    model.addElement(b);
                }
                lstBlockChain.setModel(model);
            } catch (Exception ex) {
                System.getLogger(TemplarCoin.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
            }
            //------------------------------------      
        });

    }

