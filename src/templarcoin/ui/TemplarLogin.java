    public void updateUI() {
        String users[] = new File("./").list();
        DefaultListModel<String> model = new DefaultListModel();
        for (String user : users) {
            if (user.endsWith(".priv")) {
                model.addElement(user.replace(".priv", ""));
            }
        }        
        lstUsers.setModel( model);
    }

