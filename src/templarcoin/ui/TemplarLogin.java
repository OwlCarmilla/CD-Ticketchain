    private void brRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_brRegisterActionPerformed

        String pass1 = new String(txtRegisterPass1.getPassword());
        String pass2 = new String(txtRegisterPass2.getPassword());
        if (!pass1.equals(pass2)) {
            JOptionPane.showMessageDialog(this, "As passwords são diferentes", "Passwords diferentes", JOptionPane.WARNING_MESSAGE);
            return;
        }
        try {
            KeyPair kp = SecurityUtils.generateKeyPair(3096);
            String name = txtRegisterUsername.getText().trim();
            SecurityUtils.savePublicKey(kp.getPublic(), name);
            SecurityUtils.savePrivateKey(kp.getPrivate(), name, pass1);
            updateUI();
            JOptionPane.showMessageDialog(this, "Utilizador\n" + name + "\nCriado com sucesso", "Registar utilizadores", JOptionPane.INFORMATION_MESSAGE);

        } catch (Exception ex) {
            System.getLogger(TemplarLogin.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Registar utilizadores", JOptionPane.ERROR_MESSAGE);

        }


    }//GEN-LAST:event_brRegisterActionPerformed

    private void btLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btLoginActionPerformed
        try {
            String user = txtLoginUser.getText();
            PublicKey pub = SecurityUtils.loadPublicKey(user);
            PrivateKey priv = SecurityUtils.loadPrivateKey(user, new String(txtLoginPass.getPassword()));
            TemplarCoin gui = new TemplarCoin(user, pub, priv);
            new Thread(() -> {
                gui.setVisible(true);
            }
            ).start();
            // keep the login open to log in other users at the same time
            txtLoginPass.setText("");

        } catch (Exception ex) {
            System.getLogger(TemplarLogin.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
            JOptionPane.showMessageDialog(this, "Credenciais erradas", "Login", JOptionPane.ERROR_MESSAGE);

        }

    }//GEN-LAST:event_btLoginActionPerformed

